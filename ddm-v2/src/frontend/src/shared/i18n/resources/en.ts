//
// 用型別把這件事從「肉眼複驗」升級成「typecheck 機械保證」：漏一個 key、多一個 key、
// 或把某個 leaf 從字串改成別的型別，tsc 都會直接紅，不必等到有人切成英文親眼看到
// 殘留的中文才發現。不能直接寫 `const en: typeof zhTW`——`zh-TW.ts` 用了 `as const`，
// `typeof zhTW` 的每個 leaf 都是該中文字串本身的字面型別（如 `'切換語言'`），
// 逐字要求英文譯文等於中文字面值沒有意義（也不可能通過）。`Widen<T>` 只保留
// 「鍵的形狀」與「leaf 必須是 string」，放行不同的字串內容。
//
// 唯一的例外是**複數形**（ADR-032 B 裁決）：英文的計數字串需要 `key_one`，
// 中文沒有這個概念（CLDR 的 zh 只有 `other` 一類），所以這一類 key 兩邊
// 不可能完全對稱。放寬的方式是只多開一道窄門——允許 en 針對「zh-TW 那邊是
// 字串的 key」額外提供 `key_<複數類別>`；其餘任何多出來的 key 仍然被 excess
// property check 擋下，**缺 key 仍然是編譯錯**（R4 真正在守的就是這條）。
// 基底 key 本身仍是必填，而且**就是 `other` 形**：i18next 找不到 `key_other`
// 時會回退到基底 key（v26.3.6 實測：count=1 → `key_one`、count≠1 → 基底 key），
// 所以 en 只要多寫 `_one` 就夠，不必把 `other` 再抄一份。
type PluralCategory = 'zero' | 'one' | 'two' | 'few' | 'many' | 'other'

type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : { [K in keyof T]: Widen<T[K]> }
      & { [K in keyof T as T[K] extends string ? `${K & string}_${PluralCategory}` : never]?: string }

